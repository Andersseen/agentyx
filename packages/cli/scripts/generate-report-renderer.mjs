// Compiles src/report/templates/report.flow into the committed render function.
//
// The Flowview compiler is a development dependency: the published CLI only ever loads the
// generated JavaScript and the tiny @flowview/runtime. `--check` fails when the committed output
// no longer matches the template, so a stale renderer cannot reach a release.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { compileFlowview } from "@flowview/compiler";

const reportDir = new URL("../src/report/", import.meta.url);
const templateUrl = new URL("templates/report.flow", reportDir);
const rendererUrl = new URL("report-renderer.generated.js", reportDir);
const typesUrl = new URL("report-renderer.generated.d.ts", reportDir);

const HEADER = [
  "// Generated by packages/cli/scripts/generate-report-renderer.mjs from templates/report.flow.",
  "// Do not edit: change the template and run `pnpm report:generate`.",
  "",
].join("\n");

const source = await readFile(templateUrl, "utf8");
const result = compileFlowview(source, {
  filename: "report.flow",
  runtimeImport: "@flowview/runtime",
});

if (result.warnings.length > 0) {
  for (const warning of result.warnings) {
    console.error(
      `report.flow:${warning.line}:${warning.column} ${warning.code} ${warning.message}`,
    );
  }
  process.exit(1);
}

const outputs = [
  [rendererUrl, `${HEADER}${result.code}`],
  [
    typesUrl,
    `${HEADER}import type { ReportView } from "./view.js";\n\nexport function render(context: ReportView): string;\n`,
  ],
];

if (process.argv.includes("--check")) {
  let stale = false;
  for (const [url, expected] of outputs) {
    const actual = await readFile(url, "utf8").catch(() => undefined);
    if (actual !== expected) {
      console.error(`${fileURLToPath(url)} is stale or missing.`);
      stale = true;
    }
  }
  if (stale) {
    console.error("Run `pnpm report:generate` and commit the result.");
    process.exit(1);
  }
  console.log("Report renderer matches report.flow.");
} else {
  for (const [url, content] of outputs) await writeFile(url, content);
  console.log("Generated report renderer from report.flow.");
}
